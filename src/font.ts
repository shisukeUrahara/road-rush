export const GLYPH_W = 4;
export const GLYPH_H = 6;
/** Advance per character including the 1px gap. */
export const CHAR_ADVANCE = 5;

export function textWidth(text: string): number {
  return text.length * CHAR_ADVANCE - 1;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  const upper = text.toUpperCase();
  for (let i = 0; i < upper.length; i++) {
    const glyph = GLYPHS[upper[i]];
    if (!glyph) continue;
    const gx = x + i * CHAR_ADVANCE * scale;
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      if (!bits) continue;
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits & (1 << (GLYPH_W - 1 - col))) {
          ctx.fillRect(gx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  centerX: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawText(ctx, text, Math.round(centerX - (textWidth(text) * scale) / 2), y, color, scale);
}
